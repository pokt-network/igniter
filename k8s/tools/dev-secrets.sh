#!/usr/bin/env bash
# Creates the local Tilt dev secrets file once, if it does not exist yet.
# The values are random per machine and never committed: the file lives under
# .local/ (gitignored). Later runs leave it alone, because the provider's
# ENCRYPTION_KEY/IV must stay stable or the dev database's encrypted supplier
# keys can no longer be decrypted.
#
# Usage: k8s/tools/dev-secrets.sh <path>   (the root Tiltfile calls it)
set -euo pipefail

FILE="${1:?usage: dev-secrets.sh <path>}"

if [[ -s "$FILE" ]]; then
  exit 0
fi

mkdir -p "$(dirname "$FILE")"
umask 077
cat > "$FILE" <<EOF
# Generated by k8s/tools/dev-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Local dev only.
# Delete this file to regenerate. Then also reset the dev database
# (tilt down + delete the postgres PVC), because the provider keys in it are
# encrypted with IGNITER_DEV_PROVIDER_ENCRYPTION_KEY/IV.
IGNITER_DEV_PROVIDER_AUTH_SECRET=$(openssl rand -hex 32)
IGNITER_DEV_PROVIDER_ENCRYPTION_KEY=$(openssl rand -hex 32)
IGNITER_DEV_PROVIDER_ENCRYPTION_IV=$(openssl rand -hex 16)
IGNITER_DEV_MIDDLEMAN_AUTH_SECRET=$(openssl rand -hex 32)
IGNITER_DEV_MIDDLEMAN_NOTIFICATION_ENCRYPTION_KEY=$(openssl rand -hex 32)
EOF
echo "dev-secrets: created $FILE"
